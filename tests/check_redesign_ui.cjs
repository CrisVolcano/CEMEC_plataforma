// Prueba integral del diseño con datos sintéticos y backend/almacenamiento aislados.
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {spawn,execFileSync}=require('node:child_process');
const assert=require('node:assert/strict');
const project=path.resolve(__dirname,'..');
const cache=path.join(project,'.conda-env/.npm-cache/_npx');
const dir=fs.readdirSync(cache).map(name=>path.join(cache,name,'node_modules/playwright')).find(dir=>fs.existsSync(path.join(dir,'package.json'))&&JSON.parse(fs.readFileSync(path.join(dir,'package.json'))).version==='1.58.2');
const {chromium}=require(dir);
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'cemec-redesign-'));
const ready=path.join(temp,'ready.json');
const fixture=spawn(path.join(project,'.conda-env/bin/python'),[path.join(__dirname,'ui_fixture.py'),'--ready-file',ready,'--eumetsat'],{stdio:['ignore','ignore','inherit']});
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const qa=path.join(project,'runtime/redesign-qa');fs.mkdirSync(qa,{recursive:true});
(async()=>{
 let browser,page;const errors=[];
 try{
  for(let i=0;i<300&&!fs.existsSync(ready);i++){if(fixture.exitCode!==null)throw Error('El servidor QA no inició');await delay(100);}
  const {port}=JSON.parse(fs.readFileSync(ready));
  browser=await chromium.launch({channel:'chrome',headless:true});
  page=await browser.newPage({viewport:{width:1500,height:1100}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`http://127.0.0.1:${port}`,{waitUntil:'networkidle'});
  await page.locator('.cemec-page-heading h1').waitFor();
  const navigation=page.getByRole('navigation',{name:'Navegación principal'});
  assert.equal(await navigation.getByRole('button').count(),3);
  assert.equal(await page.getByRole('combobox',{name:'Instrumento',exact:true}).isVisible(),false,'Los filtros avanzados se agrupan');
  for(const kind of ['municipio','protegida','manejo','region']){
   await page.getByRole('combobox',{name:'Unidad de análisis',exact:true}).selectOption(kind);
   await page.waitForTimeout(250);
   assert.equal(await page.getByRole('combobox',{name:'Unidad de análisis',exact:true}).inputValue(),kind);
  }
  await page.getByRole('combobox',{name:'Unidad administrativa',exact:true}).selectOption('region-peten');
  await page.getByRole('button',{name:/Más filtros/}).click();
  await page.getByRole('combobox',{name:'Confianza',exact:true}).selectOption('h');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Quitar Confianza: Alta',exact:true}).waitFor();
  await page.getByRole('button',{name:'Quitar Confianza: Alta',exact:true}).click();
  await page.getByRole('button',{name:/Más filtros/}).click();
  assert.equal(await page.getByRole('combobox',{name:'Confianza',exact:true}).inputValue(),'all');
  await page.getByRole('button',{name:'Ver resultados',exact:true}).click();
  await page.getByText('Administración',{exact:true}).click();
  await page.getByRole('button',{name:'Ajustes',exact:true}).click();
  await page.getByRole('button',{name:'Sincronizar Sentinel-3',exact:true}).click();
  await page.getByText(/Última sincronización Sentinel-3:/).waitFor({timeout:120000});
  await page.getByRole('button',{name:'Cerrar panel',exact:true}).click();
  await page.getByTestId('detections-count').filter({hasText:/^17$/}).waitFor();
  const dates=await page.locator('input[type=date]').evaluateAll(inputs=>inputs.map(input=>input.value));
  await page.getByRole('button',{name:'Fuentes y sensores',exact:true}).click();
  await page.getByRole('heading',{name:'Entender las diferencias',exact:true}).waitFor();
  await page.getByText('La fuente distribuye los datos; el sensor realiza la observación.',{exact:true}).waitFor();
  await page.screenshot({path:path.join(qa,'sources.png'),fullPage:true});
  await page.getByRole('button',{name:'Volver a Explorar',exact:true}).click();
  assert.deepEqual(await page.locator('input[type=date]').evaluateAll(inputs=>inputs.map(input=>input.value)),dates,'La navegación conserva las fechas');
  await page.getByRole('button',{name:/Más filtros/}).click();
  assert.equal(await page.getByRole('combobox',{name:'Origen',exact:true}).inputValue(),'eumetsat');
  await page.getByRole('combobox',{name:'Origen',exact:true}).selectOption('all');
  await page.getByRole('combobox',{name:'Instrumento',exact:true}).selectOption('all');
  await page.getByRole('button',{name:'Ver resultados',exact:true}).click();
  await page.getByRole('button',{name:'Comparar observaciones',exact:true}).click();
  await page.getByRole('heading',{name:'Una mirada complementaria',exact:true}).waitFor();
  await page.getByRole('combobox',{name:'Sensor de comparación A',exact:true}).selectOption('eumetsat|SLSTR');
  await page.getByRole('combobox',{name:'Sensor de comparación B',exact:true}).selectOption('firms|MODIS');
  await page.waitForTimeout(1200);
  await page.getByRole('button',{name:'Acercar',exact:true}).first().click();
  await page.waitForTimeout(1200);
  const mapTransforms=await page.locator('.cemec-comparison-map').evaluateAll(cards=>cards.map(card=>card.querySelector('.map-unit-label').style.transform));
  assert.equal(mapTransforms[0],mapTransforms[1],'Los mapas de comparación comparten el zoom y la extensión');
  await page.screenshot({path:path.join(qa,'comparison.png'),fullPage:true});
  await page.getByRole('button',{name:'Generar reporte de comparación',exact:true}).click();
  await page.getByRole('dialog',{name:'Reporte de la selección',exact:true}).waitFor();
  await page.screenshot({path:path.join(qa,'report-scope.png')});
  let downloaded=page.waitForEvent('download',{timeout:120000});
  await page.getByRole('button',{name:'Generar PDF',exact:true}).click();
  const pdf=path.join(qa,'comparison-report.pdf');await (await downloaded).saveAs(pdf);
  assert.ok(fs.readFileSync(pdf).subarray(0,5).equals(Buffer.from('%PDF-')));
  const text=execFileSync('pdftotext',[pdf,'-'],{encoding:'utf8'});
  assert.match(text,/Comparación seleccionada/);assert.match(text,/EUMETSAT/);assert.match(text,/Consultas y disponibilidad/);
  assert.match(text,/SLSTR/);assert.match(text,/confianza/);assert.match(text,/17/);
  assert.equal((await page.getByRole('alert').allTextContents()).length,0,'El reporte se generó sin errores');
  await page.getByRole('button',{name:'Volver a Explorar',exact:true}).click();
  await page.getByRole('button',{name:'Descargar datos',exact:true}).click();
  downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'CSV',exact:true}).click();
  const csv=path.join(qa,'selected.csv');await (await downloaded).saveAs(csv);
  assert.match(fs.readFileSync(csv,'utf8'),/EUMETSAT/);
  await page.waitForTimeout(1200);
  await page.screenshot({path:path.join(qa,'desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Datos',exact:true}).click();
  await page.getByRole('heading',{name:'Datos y trazabilidad',exact:true}).waitFor();
  assert.ok(await page.getByRole('link',{name:'Límites · GeoParquet',exact:true}).getAttribute('href'));
  await page.getByRole('button',{name:'Volver a Explorar',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(800);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Sin desbordamiento horizontal en móvil');
  await page.locator('.cemec-controls>summary').click();
  await page.getByRole('button',{name:/Más filtros/}).click();
  await page.screenshot({path:path.join(qa,'mobile-filters.png')});
  await page.keyboard.press('Escape');
  await page.screenshot({path:path.join(qa,'mobile.png'),fullPage:true});
  assert.deepEqual(errors,[],'Sin errores JavaScript al cambiar vistas, filtros y generar reportes');
  console.log('QA diseño OK: cuatro unidades, filtros, navegación, comparación, PDF, CSV, móvil y teclado. Datos sintéticos aislados.');
 }catch(error){if(page){await page.screenshot({path:path.join(qa,'error.png'),fullPage:true});console.error('Errores JS',errors);console.error((await page.locator('body').innerText()).slice(-2200));}throw error;}
 finally{if(browser)await browser.close();const stopped=new Promise(resolve=>fixture.once('exit',resolve));fixture.kill('SIGTERM');if(fixture.exitCode===null)await stopped;fs.rmSync(temp,{recursive:true,force:true});}
})().catch(error=>{console.error(error.message);process.exitCode=1;});
